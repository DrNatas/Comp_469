def load_agent_module():
    import importlib.util

    spec = importlib.util.spec_from_file_location("student_agent_under_test", AGENT_PATH)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules["student_agent_under_test"] = module
    spec.loader.exec_module(module)
    return module


class Chapter2Base(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.module = load_agent_module()
        cls.maze = MazeModel(TEST_LEVEL)

    def new_agent(self):
        return self.module.PacManAgent(self.maze)

    def make_percept(self, agent, **overrides):
        """Build a percept containing whatever fields the student declared."""
        defaults = {
            "player": (2, 2),
            "current_direction": DIRECTIONS["RIGHT"],
            "pellets": frozenset({(2, 3), (1, 1)}),
            "power_pellets": frozenset(),
            "ghosts": tuple(),
            "released_ghosts": tuple(),
            "legal_actions": (
                DIRECTIONS["LEFT"],
                DIRECTIONS["RIGHT"],
                DIRECTIONS["UP"],
                DIRECTIONS["DOWN"],
            ),
            "frightened_time_remaining": 0.0,
        }
        defaults.update(overrides)
        declared = [f.name for f in dataclasses.fields(agent.percept_class)]
        return agent.percept_class(**{name: defaults[name] for name in declared})


